#[no_mangle]
#[no_mangle]
fn crc_word_big(data: u64) -> u64 {
    let mut data = data;
    for _ in 0..8 {
        data = (data << 8) ^ CRC_BIG_TABLE[((data >> 56) & 0xff) as usize];
    }
    data
}
